const_POI_URL="https://maps.six.nsw.gov.au/arcgis/rest/services/public/NSW_POI/MapServer/0/query"
const_POI_RADIUS=5000 

# Kill all previous open nc background processes
# then open netcat in the background, waiting 1ms
# then obtaining the IP and PORT to print before 
# killing again to then print.
pkill nc
nc -lkv 1234 &   # &: in background
sleep 1
IP=$(ifconfig eth0 | awk "NR==2" | awk '{print $2}' | awk -F: '{print $2}')
PORT=$(ss -ltn | grep -i "LISTEN" | awk "NR==1" |  awk '{print $4}' |  awk -F: '{print $2}')
pkill nc

echo "The server is running at $IP, port=$PORT"

function e() {
    echo "$1" >&2
    echo "$1"
}

function handleAssignment() {
    HTMLPAGE=$(curl -s https://www.sydney.edu.au/units/INFO1112/2026-S2C-ND-CC)
    if [ $? -ne 0 ]; then
        e "Error: could not download unit page"
        return 1
    fi

    HTMLPAGE=$(echo "$HTMLPAGE" | html2text -width 1000 | grep -A2 "Assignment 2" )
    
    echo "$HTMLPAGE" >&2

    # from https://stackoverflow.com/questions/22190902/cut-or-awk-command-to-print-first-field-of-first-row
    ASSIGNMENT_TITLE=$(echo "$HTMLPAGE" | awk "NR==1" | awk -F'  +' '{print $2}')
    ASSIGNMENT_TOPIC=$(echo "$HTMLPAGE" | awk "NR==2" | awk -F'  +' '{print $2}') # The true field is 'Programming task - Networking Concepts' NOT just 'Networking'. This is an error in the assignment description.
    ASSIGNMENT_DUE_DATE=$(echo "$HTMLPAGE" | awk "NR==2" | awk -F'  +' '{print $4}' | awk -F: '{print $2":"$3}')
    ASSIGNMENT_POINTS=$(echo "$HTMLPAGE" | awk "NR==2" | awk -F'  +' '{print $3}' | awk -F'%' '{print $1}')

    ASSIGNMENT_JSON=$(jq -n --arg title "$ASSIGNMENT_TITLE" --arg topic "$ASSIGNMENT_TOPIC" --arg due "$ASSIGNMENT_DUE_DATE" --argjson points "$ASSIGNMENT_POINTS" '{title: $title, topic: $topic, due_date: $due, points: $points}')

    echo "$ASSIGNMENT_JSON"
}

function handlePopulation() {
    CSVPAGE=$(curl -s https://dbr.abs.gov.au/processedData/csv/STE_1.csv)
    if [ $? -ne 0 ]; then
        e "Error: could not download NSW population data"
        return 1
    fi

    POPULATION=$(echo "$CSVPAGE" | awk "NR==2" | awk -F, '{print $NF}')
    echo "Population of NSW: $POPULATION" >&2

    # the API sends a CSV which has CRLF (windows stuff) formatting so must strip using tr
    # from https://www.tutorialspoint.com/awk/awk_loops.htm 
    echo "$CSVPAGE" | tr -d '\r' | awk -F, '  
    NR==1          { for (i=4; i<=NF; i++) year[i] = $i }
    $1=="ERP_P_20" { for (i=4; i<=NF; i++) if ($i != "") print year[i] "," $i }' > population_data.csv

    if [ ! -s population_data.csv ]; then
        e "Error: no population data found in the CSV"
        return 1
    fi

    # AI acknowledgement: Python code was generated by Claude Opus 5.5 (Anthropic)
    # See the chat link here: https://claude.ai/share/e028bc17-6963-43c9-9d92-349a12d6c9ec 
    # The code was modified to fit the problem solution closer.
    python3 - population_data.csv population.png <<'PYEOF'
import sys
import matplotlib
matplotlib.use("Agg")   # no display in the container, so render straight to file
import matplotlib.pyplot as plt
from matplotlib.ticker import FuncFormatter

data_file, out_file = sys.argv[1], sys.argv[2]

years, populations = [], []
with open(data_file) as f:
    for line in f:
        if line.strip():
            year, population = line.strip().split(",")
            years.append(int(year))
            populations.append(float(population))

plt.plot(years, populations, marker="o")
plt.title("NSW Estimated Resident Population")
plt.xlabel("Year")
plt.ylabel("Population")
plt.xticks(years)
plt.gca().yaxis.set_major_formatter(FuncFormatter(lambda v, _: f"{v:,.0f}"))
plt.grid(True, alpha=0.3)
plt.tight_layout()
plt.savefig(out_file)
PYEOF

    if [ $? -ne 0 ] || [ ! -s population.png ]; then
        e "Error: could not generate population.png"
        return 1
    fi

    echo "population.png generated, sending to client" >&2
    cat population.png
}


function handlePOI() {
    # grep -Eq '^-?[0-9.]+,-?[0-9.]+$'
    ARG="$1"

    if echo "$ARG" | grep -Eq '^-?[0-9.]+,-?[0-9.]+$'; then
        poi_LATITUDE=$(echo "$ARG" | awk -F, '{print $1}')
        poi_LONGITUDE=$(echo "$ARG" | awk -F, '{print $2}')
        # echo "coordinates latitude=$poi_LATITUDE longitude=$poi_LONGITUDE" >&2
        getPOIByCoords "$poi_LATITUDE" "$poi_LONGITUDE"
    else
        NAME=$(echo "$ARG")
        # echo "POI name ${NAME^^}" >&2
        getPOIByName "${NAME^^}"
    fi

}

